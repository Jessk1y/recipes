const NOISE = /^(?:крупн\S*|средн\S*|небольш\S*|маленьк\S*|свеж\S*|комнатн\S*|температур\S*|с[0-3]|\d+(?:[.,]\d+)?%)$/;

// слова названия: нижний регистр, ё→е, без шума (размер, категория яйца, % жирности)
function tokens(s, parensAsWords) {
  s = String(s).toLowerCase().replace(/ё/g, "е");
  s = parensAsWords ? s.replace(/[()]/g, " ") : s.replace(/\([^)]*\)/g, " ");
  return (s.match(/[а-яa-z0-9%.,]+/g) || [])
    .map((w) => w.replace(/^[.,]+|[.,]+$/g, ""))
    .filter((w) => w && !NOISE.test(w));
}
// порядок слов не важен: «масло сливочное» = «сливочное масло»
const keyOf = (toks) => toks.slice().sort().join(" ");

const BY_KEY = new Map();
PRODUCTS.forEach((p) => {
  [p.name, ...p.alias].forEach((n) => BY_KEY.set(keyOf(tokens(n, true)), p));
});

export function productInfo(name) {
  const withParens = keyOf(tokens(name, true));
  const plain = keyOf(tokens(name, false));
  const p = BY_KEY.get(withParens) || BY_KEY.get(plain);
  if (p) return { key: keyOf(tokens(p.name, true)), density: p.d || 0, pref: p.pref || "g" };
  return { key: plain || withParens || String(name).trim().toLowerCase(), density: 0, pref: "g" };
}
export const canonKey = (name) => productInfo(name).key;

// Названия для подсказок в редакторе рецептов (основные + синонимы словаря)
export const productNames = () => [...new Set(PRODUCTS.flatMap((p) => [p.name, ...p.alias]))];
